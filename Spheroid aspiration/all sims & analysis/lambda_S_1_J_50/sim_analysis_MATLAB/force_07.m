
scriptPath = fileparts(mfilename('fullpath'));
projectPath = fileparts(scriptPath);
basePath_asp = fullfile(projectPath, 'asp_forces', 'force_0.7');

% Find all simulation folders inside force_0.7.
simulationFolders = dir(basePath_asp);
simulationFolders = simulationFolders([simulationFolders.isdir]);
simulationFolders = simulationFolders( ...
    ~startsWith({simulationFolders.name}, '.'));

N = length(simulationFolders);
filePaths_asp = cell(1, N);

for i = 1:N
    filePaths_asp{i} = fullfile( ...
        basePath_asp, ...
        simulationFolders(i).name, ...
        'logger.csv');
end

suffix = sprintf('%02d', 7);
asp_force = 0.7;
clipping = 2; % aspiration until this point is ignored

[timeCommon, meanVal, semVal, lower_k, higher_k, mean_k, ...
    lower_tau, higher_tau, mean_tau, lower_xi_f, higher_xi_f, mean_xi_f, lower_xi_t, higher_xi_t, mean_xi_t, ...
    lower_L_p, higher_L_p, mean_L_p, lower_L_end, higher_L_end, mean_L_end, fitVal] = ...
    process_sim_block(filePaths_asp, clipping, asp_force);

eval(sprintf('timeCommon_%s = timeCommon;', suffix));
eval(sprintf('mean_%s       = meanVal;',    suffix));
eval(sprintf('sem_%s        = semVal;',     suffix));
eval(sprintf('lower_k_%s    = lower_k;',    suffix));
eval(sprintf('higher_k_%s   = higher_k;',   suffix));
eval(sprintf('mean_k_%s     = mean_k;',     suffix));
eval(sprintf('lower_tau_%s    = lower_tau;',    suffix));
eval(sprintf('higher_tau_%s   = higher_tau;',   suffix));
eval(sprintf('mean_tau_%s     = mean_tau;',     suffix));
eval(sprintf('lower_xi_f_%s    = lower_xi_f;',    suffix));
eval(sprintf('higher_xi_f_%s   = higher_xi_f;',   suffix));
eval(sprintf('mean_xi_f_%s     = mean_xi_f;',     suffix));
eval(sprintf('lower_xi_t_%s    = lower_xi_t;',    suffix));
eval(sprintf('higher_xi_t_%s   = higher_xi_t;',   suffix));
eval(sprintf('mean_xi_t_%s     = mean_xi_t;',     suffix));
eval(sprintf('lower_L_p_%s    = lower_L_p;',    suffix));
eval(sprintf('higher_L_p_%s   = higher_L_p;',   suffix));
eval(sprintf('mean_L_p_%s     = mean_L_p;',     suffix));
eval(sprintf('lower_L_end_%s    = lower_L_end;',    suffix));
eval(sprintf('higher_L_end_%s   = higher_L_end;',   suffix));
eval(sprintf('mean_L_end_%s     = mean_L_end;',     suffix));
eval(sprintf('fit_%s     = fitVal;',     suffix));

save(sprintf('block_%s_results.mat', suffix), ...
    sprintf('timeCommon_%s', suffix), ...
    sprintf('mean_%s', suffix), ...
    sprintf('sem_%s', suffix), ...
    sprintf('lower_k_%s', suffix), ...
    sprintf('higher_k_%s', suffix), ...
    sprintf('mean_k_%s', suffix), ...
    sprintf('lower_tau_%s', suffix), ...
    sprintf('higher_tau_%s', suffix), ...
    sprintf('mean_tau_%s', suffix), ...
    sprintf('lower_xi_f_%s', suffix), ...
    sprintf('higher_xi_f_%s', suffix), ...
    sprintf('mean_xi_f_%s', suffix), ...
    sprintf('lower_xi_t_%s', suffix), ...
    sprintf('higher_xi_t_%s', suffix), ...
    sprintf('mean_xi_t_%s', suffix), ...
    sprintf('lower_L_p_%s', suffix), ...
    sprintf('higher_L_p_%s', suffix), ...
    sprintf('mean_L_p_%s', suffix), ...
    sprintf('lower_L_end_%s', suffix), ...
    sprintf('higher_L_end_%s', suffix), ...
    sprintf('mean_L_end_%s', suffix), ...
    sprintf('fit_%s', suffix))

